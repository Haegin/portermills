defmodule Portermills.EmailInviteFixtures do
  @moduledoc """
  DKIM-signed emails for the email invite tests, generated by
  `test/fixtures/email_invites/generate.py`, and a stand-in for the DNS lookup of their
  public keys.
  """

  @dir Path.expand("../fixtures/email_invites", __DIR__)

  def email(name), do: File.read!(Path.join(@dir, name <> ".eml"))

  @doc "Serves `dns_txt.txt` in place of DNS (configured as the DKIM key lookup in test)."
  def dns_txt(name) do
    @dir
    |> Path.join("dns_txt.txt")
    |> File.read!()
    |> String.split("\n", trim: true)
    |> Enum.find_value({:error, :no_key_in_dns}, fn line ->
      case String.split(line, " ", parts: 2) do
        [^name, record] -> {:ok, [record]}
        _ -> nil
      end
    end)
  end
end
